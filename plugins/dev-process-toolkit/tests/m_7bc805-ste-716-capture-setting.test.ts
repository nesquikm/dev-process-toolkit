// STE-716 (M_7bc805) AC.1 + AC.24 — the `tracking.tool_calls` switch, its
// loader wiring, the `tracking` defaults merge and the composer list.
//
// The switch is read through the loader (`loadProjectSection(root,
// "tracking")`) and the `toolCallsSwitchOn` export, which reads any refusal as
// off. All names, paths and values are synthetic.

import { afterAll, describe, expect, test } from "bun:test";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { PLUGIN_ROOT, SETTINGS_HEAD, cleanupTemps, makeTree, tempDir } from "./_m_7bc805_gate_outcome_fixture";

type AnyMod = Record<string, any>;

afterAll(cleanupTemps);

async function S(): Promise<AnyMod> {
  return (await import("../adapters/_shared/src/project_settings")) as AnyMod;
}

const NON_MIGRATED_MD = "<!-- generated by /dev-process-toolkit:setup -->\n# P\n";

function settingsTree(label: string, body: string, claudeMd = NON_MIGRATED_MD): string {
  const root = tempDir(label);
  mkdirSync(join(root, "specs"), { recursive: true });
  writeFileSync(join(root, "specs", "settings.yaml"), body);
  writeFileSync(join(root, "CLAUDE.md"), claudeMd);
  return root;
}

const ON = `${SETTINGS_HEAD}tracking:\n  tool_calls:\n    enabled: true\n`;

// ===========================================================================
// AC-STE-716.1 — the switch shape and its loader wiring
// ===========================================================================

describe("AC-STE-716.1 the tool_calls switch", () => {
  test("an absent key or section reads enabled: false; { enabled: true } reads true", async () => {
    const m = await S();
    const absentKey = settingsTree("tc-absent-key", `${SETTINGS_HEAD}tracking:\n  token_stats:\n    enabled: false\n`);
    expect(m.loadProjectSettings(absentKey).settings.tracking.tool_calls).toEqual({ enabled: false });
    const absentSection = settingsTree("tc-absent-section", SETTINGS_HEAD);
    expect(m.loadProjectSettings(absentSection).settings.tracking.tool_calls).toEqual({ enabled: false });
    const on = settingsTree("tc-on", ON);
    expect(m.loadProjectSettings(on).settings.tracking.tool_calls.enabled).toBe(true);
  });

  test("a legacy tree and a tree with no settings read tool_calls.enabled: false", async () => {
    const m = await S();
    for (const state of ["legacy", "none"] as const) {
      const root = makeTree(`tc-${state}`, state);
      expect({ state, tc: m.loadProjectSettings(root).settings.tracking.tool_calls }).toEqual({ state, tc: { enabled: false } });
    }
  });

  test("`tool_calls: { enabled: yes }` and a bare `tool_calls: true` throw SettingsShapeError", async () => {
    const m = await S();
    const yes = settingsTree("tc-yes", `${SETTINGS_HEAD}tracking:\n  tool_calls: { enabled: yes }\n`);
    expect(() => m.loadProjectSettings(yes)).toThrow(m.SettingsShapeError);
    const bare = settingsTree("tc-bare", `${SETTINGS_HEAD}tracking:\n  tool_calls: true\n`);
    expect(() => m.loadProjectSettings(bare)).toThrow(m.SettingsShapeError);
  });

  test("settingsKeyOrder names tool_calls after gate_outcomes; tracking.tool_calls closes on {enabled}; NEW_KEYS holds it", async () => {
    const m = await S();
    // Amended by AC-STE-774.1 (M_4daa6e): STE-774 adds review_findings after tool_calls.
    expect(m.settingsKeyOrder("tracking")).toEqual(["token_stats", "gate_outcomes", "tool_calls", "review_findings"]);
    expect(m.settingsKeyOrder("tracking.tool_calls")).toEqual(["enabled"]);
    expect(m.NEW_KEYS).toContain("tracking.tool_calls");
  });

  test("a modelled fresh /setup writes a settings file with no tool_calls key", async () => {
    const m = await S();
    const root = tempDir("tc-fresh-setup");
    writeFileSync(join(root, "CLAUDE.md"), NON_MIGRATED_MD);
    m.writeProjectSettings(
      root,
      { schema_version: 1, min_dpt_version: "3.0.0", tracking: { token_stats: { enabled: false } }, verification: { verify_skill: "synthetic-skill" } },
      { create: true },
    );
    const text = readFileSync(join(root, "specs", "settings.yaml"), "utf-8");
    expect(text).toContain("token_stats");
    expect(text).not.toContain("tool_calls");
    // And no shipped /setup surface names the key (the NEW_KEYS walk of AC-STE-710.16 covers code).
    for (const rel of ["skills/setup/SKILL.md", "docs/setup-reference.md"]) {
      expect({ rel, names: readFileSync(join(PLUGIN_ROOT, rel), "utf-8").includes("tool_calls") }).toEqual({ rel, names: false });
    }
  });

  test("on a legacy tree no legacy home gains the key: the legacy view reads it off and CLAUDE.md is unchanged", async () => {
    const m = await S();
    const root = makeTree("tc-legacy-home", "legacy");
    const before = readFileSync(join(root, "CLAUDE.md"), "utf-8");
    expect(m.loadProjectSettings(root).settings.tracking.tool_calls).toEqual({ enabled: false });
    expect(readFileSync(join(root, "CLAUDE.md"), "utf-8")).toBe(before);
    expect(before).not.toContain("tool_calls");
  });

  test("docs/settings-reference.md names tracking.tool_calls with its type, default and no legacy home, as a STE-716 key", () => {
    const doc = readFileSync(join(PLUGIN_ROOT, "docs", "settings-reference.md"), "utf-8");
    const row = doc.split("\n").find((l) => l.startsWith("| `tracking.tool_calls` |"));
    expect(row).toBeDefined();
    expect(row!).toContain("`{ enabled: false }`");
    expect(row!).toContain("STE-716");
    expect(row!).toMatch(/no legacy home/);
  });

  // The AC-STE-706.12 walk, re-run against the MAPPING table of the loader suite.
  const LOADER_SUITE = join(PLUGIN_ROOT, "tests", "m_94e6f7-ste-706-settings-loader.test.ts");
  const ROW = '"tracking.tool_calls": { kind: "new", fr: "STE-716", note: "no legacy home" },';

  function blockOf(src: string, opener: string, closer: string): string {
    const at = src.indexOf(opener);
    expect(at).toBeGreaterThanOrEqual(0);
    return src.slice(at, src.indexOf(closer, at));
  }
  function mappedKeys(src: string): Set<string> {
    const block = blockOf(src, "const MAPPING: Record<string, Row> = {", "\n};");
    return new Set([...block.matchAll(/^\s+"?([a-z_]+(?:\.[a-z_]+)*)"?:\s*\{\s*kind:/gm)].map((x) => x[1]!));
  }
  function leafBlocks(src: string): Set<string> {
    const block = blockOf(src, "const LEAF_BLOCKS = new Set([", "]);");
    return new Set([...block.matchAll(/"([a-z_.]+)"/g)].map((x) => x[1]!));
  }
  async function unmapped(keys: Set<string>, leaves: Set<string>, extra?: [string, string]): Promise<string[]> {
    const base = (await S()).settingsKeyOrder as (p: string) => readonly string[];
    const order = (p: string): readonly string[] => (extra && p === extra[0] ? [...base(p), extra[1]] : base(p));
    const walk = (prefix: string): string[] => {
      const out: string[] = [];
      for (const k of order(prefix)) {
        const p = prefix ? `${prefix}.${k}` : k;
        if (leaves.has(p) || order(p).length === 0) out.push(p);
        else out.push(...walk(p));
      }
      return out;
    };
    // BINDING_KEYS rows are generated, not written; only the two sections under test are graded.
    return walk("").filter((p) => (p.startsWith("tracking") || p.startsWith("orchestration")) && !keys.has(p));
  }

  test("the AC-STE-706.12 table holds the new row, LEAF_BLOCKS holds the path, and the walk finds every path mapped", async () => {
    const src = readFileSync(LOADER_SUITE, "utf-8");
    expect(src).toContain(ROW);
    expect(leafBlocks(src).has("tracking.tool_calls")).toBe(true);
    expect(await unmapped(mappedKeys(src), leafBlocks(src))).toEqual([]);
  });

  test("the planted-knob control still reports only orchestration.skip_gates", async () => {
    const src = readFileSync(LOADER_SUITE, "utf-8");
    expect(await unmapped(mappedKeys(src), leafBlocks(src), ["orchestration", "skip_gates"])).toEqual(["orchestration.skip_gates"]);
  });

  test("CONTROL: deleting the new MAPPING row in a copy turns the walk red on tracking.tool_calls", async () => {
    const src = readFileSync(LOADER_SUITE, "utf-8");
    const copy = src.replace(ROW, "");
    expect(copy).not.toBe(src);
    expect(await unmapped(mappedKeys(copy), leafBlocks(copy))).toEqual(["tracking.tool_calls"]);
  });

  // --- interaction rows (per-section validation, the migrated-tree rule) ----

  test("toolCallsSwitchOn: true for an explicit true; false, absent, legacy and none read off", async () => {
    const m = await S();
    expect(typeof m.toolCallsSwitchOn).toBe("function");
    expect(m.toolCallsSwitchOn(settingsTree("tcs-on", ON))).toBe(true);
    expect(m.toolCallsSwitchOn(settingsTree("tcs-false", `${SETTINGS_HEAD}tracking:\n  tool_calls:\n    enabled: false\n`))).toBe(false);
    expect(m.toolCallsSwitchOn(settingsTree("tcs-absent", SETTINGS_HEAD))).toBe(false);
    expect(m.toolCallsSwitchOn(makeTree("tcs-legacy", "legacy"))).toBe(false);
    expect(m.toolCallsSwitchOn(makeTree("tcs-none", "none"))).toBe(false);
  });

  test("a malformed tracking.token_stats beside tool_calls: { enabled: true } makes toolCallsSwitchOn return false", async () => {
    const m = await S();
    const root = settingsTree("tcs-bad-token", `${SETTINGS_HEAD}tracking:\n  token_stats: yes\n  tool_calls:\n    enabled: true\n`);
    expect(() => m.toolCallsSwitchOn(root)).not.toThrow();
    expect(m.toolCallsSwitchOn(root)).toBe(false);
  });

  test("a malformed video section beside it leaves it true", async () => {
    const m = await S();
    const root = settingsTree("tcs-bad-video", `${ON}video: 7\n`);
    expect(() => m.loadProjectSettings(root)).toThrow(m.SettingsShapeError); // CONTROL: the video section IS malformed
    expect(m.toolCallsSwitchOn(root)).toBe(true);
  });

  test("a non-migrated tree whose settings file holds tool_calls on but no min_dpt_version reads false", async () => {
    const m = await S();
    const root = settingsTree("tcs-foreign", `schema_version: 1\ntracking:\n  tool_calls:\n    enabled: true\n`);
    expect(m.isForeignSettingsFile(root)).toBe(true);
    expect(m.toolCallsSwitchOn(root)).toBe(false);
  });

  test("a migrated tree (pointer line in ## Project Settings) whose settings file lost min_dpt_version reads false without throwing", async () => {
    const m = await S();
    const md = `${NON_MIGRATED_MD}\n## Project Settings\n\n${m.renderSettingsPointer("3.0.0")}`;
    const root = settingsTree("tcs-migrated", `schema_version: 1\ntracking:\n  tool_calls:\n    enabled: true\n`, md);
    expect(m.isForeignSettingsFile(root)).toBe(false); // CONTROL: the migrated rule applies, so the file is the toolkit's
    expect(() => m.loadProjectSection(root, "tracking")).toThrow(); // and the loader refuses it
    expect(() => m.toolCallsSwitchOn(root)).not.toThrow();
    expect(m.toolCallsSwitchOn(root)).toBe(false);
  });
});

