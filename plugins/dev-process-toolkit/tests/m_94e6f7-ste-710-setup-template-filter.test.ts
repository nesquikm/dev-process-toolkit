// STE-710 AC-STE-710.17 — setup from a template.
//
// Module under test: adapters/_shared/src/setup/template_copy.ts (new). The
// shape these tests assume:
//
//   planTemplateCopy(templateRoot, targetRoot, opts) =>
//     { files: Record<string, string>; dropped: string[]; report: string }
//
//   opts = { mode: "per-category", selection: string[] }   // template-relative paths
//        | { mode: "whole-project" }                       // the template's whole tree minus .git
//
// `files` is the proposed content of every selected file, keyed by its
// template-relative path, BEFORE the Step 5 diff and before the model's
// project-identifying rewrite (Step 4). A copied `specs/settings.yaml` has
// passed the NEW_KEYS filter: every key listed in `NEW_KEYS` is dropped, a
// parent the drop leaves empty goes with it, and every other byte is
// unchanged. `dropped` lists the dropped dotted keys; `report` is the text
// the Step 5 preview and the closing report carry, naming each one. The plan
// writes nothing. A 3.x template (one carrying `specs/settings.yaml`) whose
// per-category selection holds CLAUDE.md without the settings file, or the
// settings file without CLAUDE.md, refuses in NFR-10 shape naming both files.
//
// All names, paths and values are synthetic.

import { afterAll, describe, expect, test } from "bun:test";
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve } from "node:path";

import { NEW_KEYS } from "../adapters/_shared/src/project_settings";

const PLUGIN = resolve(import.meta.dir, "..");
const MOD_PATH = join(PLUGIN, "adapters", "_shared", "src", "setup", "template_copy.ts");

// eslint-disable-next-line @typescript-eslint/no-explicit-any
type Any = any;
let loaded: Any = null;
let loadError: unknown = null;
try {
  loaded = await import(MOD_PATH);
} catch (e) {
  loadError = e;
}
function M(): Any {
  if (!loaded) throw new Error(`setup/template_copy.ts is not loadable: ${loadError instanceof Error ? loadError.message : String(loadError)}`);
  return loaded;
}

const ROOTS: string[] = [];
afterAll(() => {
  for (const r of ROOTS) rmSync(r, { recursive: true, force: true });
});

function tree(files: Record<string, string>): string {
  const root = mkdtempSync(join(tmpdir(), "ste710-tpl-"));
  ROOTS.push(root);
  for (const [rel, body] of Object.entries(files)) {
    const p = join(root, rel);
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, body);
  }
  return root;
}

function snapshot(root: string): Record<string, string> {
  const out: Record<string, string> = {};
  const walk = (dir: string): void => {
    for (const name of readdirSync(dir).sort()) {
      const p = join(dir, name);
      if (statSync(p).isDirectory()) walk(p);
      else out[relative(root, p)] = readFileSync(p, "latin1");
    }
  };
  walk(root);
  return out;
}

function nfr10(msg: string): void {
  expect(msg).toMatch(/^Refusing: /m);
  expect(msg).toMatch(/^Remedy: /m);
  expect(msg).toMatch(/^Context: /m);
}

function thrown(fn: () => unknown): Error {
  try {
    fn();
  } catch (e) {
    return e as Error;
  }
  throw new Error("expected a throw, got a return");
}

/** Block-style YAML lines setting every NEW_KEYS key on (`<key>: { enabled: true }` as a block). */
function newKeyLines(): string[] {
  const nested: Record<string, unknown> = {};
  for (const dotted of NEW_KEYS) {
    const parts = dotted.split(".");
    let cur = nested;
    for (const p of parts.slice(0, -1)) cur = (cur[p] ??= {}) as Record<string, unknown>;
    cur[parts[parts.length - 1]!] = { enabled: true };
  }
  const out: string[] = [];
  const emit = (obj: Record<string, unknown>, indent: string): void => {
    for (const [k, v] of Object.entries(obj)) {
      if (typeof v === "object" && v !== null) {
        out.push(`${indent}${k}:`);
        emit(v as Record<string, unknown>, `${indent}  `);
      } else {
        out.push(`${indent}${k}: ${String(v)}`);
      }
    }
  };
  emit(nested, "");
  return out;
}

const KEPT_LINES = [
  "# Template settings — synthetic",
  "schema_version: 1",
  'min_dpt_version: "2.0.0"',
  "task_tracking:",
  "  mode: linear",
  "  mcp_server: linear",
  "  linear:",
  "    team: TPL",
  "    project: Template Project   # the project-identifying value",
  "docs:",
  "  user_facing_mode: true",
  "  packages_mode: false",
];
const TEMPLATE_SETTINGS = [...KEPT_LINES, ...newKeyLines(), "release:", "  files:", "    - path: package.json", "      kind: json", "      field: version", ""].join("\n");

const TEMPLATE_CLAUDE_MD = "<!-- generated by /dev-process-toolkit:setup -->\n\n# Template Project\n\n## Project Settings\n\nProject settings live in `specs/settings.yaml`.\n";

function v3Template(): string {
  return tree({
    "CLAUDE.md": TEMPLATE_CLAUDE_MD,
    "specs/settings.yaml": TEMPLATE_SETTINGS,
    "package.json": '{ "name": "template-project", "version": "0.1.0" }\n',
    "src/index.ts": "export const x = 1;\n",
    ".git/HEAD": "ref: refs/heads/main\n",
  });
}

/** `obj` with every NEW_KEYS path deleted and every parent the deletion left empty pruned. */
function withoutNewKeys(obj: Record<string, unknown>): Record<string, unknown> {
  const out = structuredClone(obj);
  for (const dotted of NEW_KEYS) {
    const parts = dotted.split(".");
    const chain: Record<string, unknown>[] = [out];
    let cur: Record<string, unknown> | undefined = out;
    for (const p of parts.slice(0, -1)) {
      cur = cur?.[p] as Record<string, unknown> | undefined;
      if (cur) chain.push(cur);
    }
    if (!cur) continue;
    delete cur[parts[parts.length - 1]!];
    for (let i = chain.length - 1; i > 0; i--) {
      if (Object.keys(chain[i]!).length === 0) delete chain[i - 1]![parts[i - 1]!];
    }
  }
  return out;
}

function isSubsequence(before: string[], after: string[]): boolean {
  let j = 0;
  for (const l of before) if (j < after.length && l === after[j]) j++;
  return j === after.length;
}

function expectFiltered(text: string, dropped: string[], report: string): void {
  const parsed = Bun.YAML.parse(text) as Record<string, unknown>;
  const original = Bun.YAML.parse(TEMPLATE_SETTINGS) as Record<string, unknown>;
  expect(parsed).toEqual(withoutNewKeys(original));
  for (const k of NEW_KEYS) {
    expect(dropped).toContain(k);
    expect(report).toContain(k);
  }
  // Every other copied byte is unchanged: the filtered lines are the template's, in order.
  expect(isSubsequence(TEMPLATE_SETTINGS.split("\n"), text.split("\n"))).toBe(true);
  for (const l of KEPT_LINES) expect(text.split("\n")).toContain(l);
}

describe("AC-STE-710.17 setup from a template", () => {
  test("AC-.17 the fixture sets every NEW_KEYS key on (guards a vacuous filter row)", () => {
    expect(NEW_KEYS.length).toBeGreaterThan(0);
    for (const k of NEW_KEYS) {
      let cur: Any = Bun.YAML.parse(TEMPLATE_SETTINGS);
      for (const p of k.split(".")) cur = cur?.[p];
      expect([k, cur]).toEqual([k, { enabled: true }]);
    }
  });

  test("AC-.17 per-category: the landed settings file holds no NEW_KEYS key, the rest unchanged, each drop named", () => {
    const tpl = v3Template();
    const target = tree({});
    const plan = M().planTemplateCopy(tpl, target, { mode: "per-category", selection: ["CLAUDE.md", "specs/settings.yaml"] });
    expect(Object.keys(plan.files).sort()).toEqual(["CLAUDE.md", "specs/settings.yaml"]);
    expect(plan.files["CLAUDE.md"]).toBe(TEMPLATE_CLAUDE_MD);
    expectFiltered(plan.files["specs/settings.yaml"], plan.dropped, plan.report);
  });

  test("AC-.17 whole-project: the landed settings file holds no NEW_KEYS key, the rest of the tree unchanged, each drop named", () => {
    const tpl = v3Template();
    const target = tree({ "README.md": "# Target\n" });
    const plan = M().planTemplateCopy(tpl, target, { mode: "whole-project" });
    expect(Object.keys(plan.files).sort()).toEqual(["CLAUDE.md", "package.json", "specs/settings.yaml", "src/index.ts"]);
    expect(plan.files["package.json"]).toBe('{ "name": "template-project", "version": "0.1.0" }\n');
    expectFiltered(plan.files["specs/settings.yaml"], plan.dropped, plan.report);
  });

  test("AC-.17 the plan writes nothing to the target or the template", () => {
    const tpl = v3Template();
    const target = tree({ "README.md": "# Target\n" });
    const before = [snapshot(tpl), snapshot(target)];
    M().planTemplateCopy(tpl, target, { mode: "whole-project" });
    expect([snapshot(tpl), snapshot(target)]).toEqual(before);
  });

  test("AC-.17 CLAUDE.md alone refuses before the Step 5 diff, naming both files, target byte-identical", () => {
    const tpl = v3Template();
    const target = tree({});
    const before = snapshot(target);
    const err = thrown(() => M().planTemplateCopy(tpl, target, { mode: "per-category", selection: ["CLAUDE.md"] }));
    nfr10(err.message);
    expect(err.message).toContain("CLAUDE.md");
    expect(err.message).toContain("specs/settings.yaml");
    expect(snapshot(target)).toEqual(before);
  });

  test("AC-.17 specs/settings.yaml alone refuses on an empty target, naming both files, target byte-identical", () => {
    const tpl = v3Template();
    const target = tree({});
    const before = snapshot(target);
    const err = thrown(() => M().planTemplateCopy(tpl, target, { mode: "per-category", selection: ["specs/settings.yaml"] }));
    nfr10(err.message);
    expect(err.message).toContain("CLAUDE.md");
    expect(err.message).toContain("specs/settings.yaml");
    expect(snapshot(target)).toEqual(before);
  });

  test("AC-.17 specs/settings.yaml alone refuses on a target holding a legacy CLAUDE.md, target byte-identical", () => {
    const tpl = v3Template();
    const target = tree({ "CLAUDE.md": "# Target\n\n## Docs\n\nuser_facing_mode: false\npackages_mode: false\nchangelog_ci_owned: false\n" });
    const before = snapshot(target);
    const err = thrown(() => M().planTemplateCopy(tpl, target, { mode: "per-category", selection: ["specs/settings.yaml"] }));
    nfr10(err.message);
    expect(err.message).toContain("CLAUDE.md");
    expect(err.message).toContain("specs/settings.yaml");
    expect(snapshot(target)).toEqual(before);
  });

  test("AC-.17 a 2.x template (no settings file) copied per category with only CLAUDE.md lands the v2.101.4 bytes", () => {
    const legacyMd = "# Template Project\n\n## Docs\n\nuser_facing_mode: true\npackages_mode: false\nchangelog_ci_owned: false\n";
    const tpl = tree({ "CLAUDE.md": legacyMd, "package.json": "{}\n" });
    const target = tree({});
    const plan = M().planTemplateCopy(tpl, target, { mode: "per-category", selection: ["CLAUDE.md"] });
    expect(plan.files).toEqual({ "CLAUDE.md": legacyMd });
    expect(plan.dropped).toEqual([]);
  });

  test("AC-.17 skills/setup-template/SKILL.md names the NEW_KEYS filter and the pair refusal", () => {
    const body = readFileSync(join(PLUGIN, "skills", "setup-template", "SKILL.md"), "utf8");
    expect(body).toContain("planTemplateCopy");
    expect(body).toContain("NEW_KEYS");
    const paras = body.split(/\n\s*\n/);
    expect(paras.some((p) => /refus/i.test(p) && p.includes("CLAUDE.md") && p.includes("specs/settings.yaml"))).toBe(true);
    expect(paras.some((p) => p.includes("NEW_KEYS") && /drop/i.test(p) && /preview|report/i.test(p))).toBe(true);
  });
});

// AC-STE-710.13 guard-specific row: the NEW_KEYS filter must also catch a key
// written in FLOW style, which a line-oriented block filter would miss.
describe("AC-STE-710.17 the NEW_KEYS filter catches flow style", () => {
  const FLOW_SETTINGS = [...KEPT_LINES, "close_out: { upgrade_offer: { enabled: true } }", "release:", "  files:", "    - path: package.json", "      kind: json", "      field: version", ""].join("\n");

  function flowTemplate(): string {
    return tree({ "CLAUDE.md": TEMPLATE_CLAUDE_MD, "specs/settings.yaml": FLOW_SETTINGS, "package.json": "{}\n" });
  }

  test("AC-.17 flow fixture sets close_out.upgrade_offer on (guards a vacuous row)", () => {
    expect(NEW_KEYS).toContain("close_out.upgrade_offer");
    expect((Bun.YAML.parse(FLOW_SETTINGS) as Any).close_out.upgrade_offer).toEqual({ enabled: true });
  });

  for (const opts of [
    { mode: "per-category", selection: ["CLAUDE.md", "specs/settings.yaml"] },
    { mode: "whole-project" },
  ] as const) {
    test(`AC-.17 ${opts.mode}: a flow-style NEW_KEYS key is dropped from the landed settings file and named in the report`, () => {
      const plan = M().planTemplateCopy(flowTemplate(), tree({}), opts);
      const text: string = plan.files["specs/settings.yaml"];
      expect(text).not.toContain("upgrade_offer");
      const parsed = Bun.YAML.parse(text) as Any;
      expect(parsed?.close_out?.upgrade_offer).toBeUndefined();
      expect(parsed.task_tracking.linear.team).toBe("TPL");
      expect(parsed.release.files).toEqual([{ path: "package.json", kind: "json", field: "version" }]);
      for (const l of KEPT_LINES) expect(text.split("\n")).toContain(l);
      expect(plan.dropped).toContain("close_out.upgrade_offer");
      expect(plan.report).toContain("close_out.upgrade_offer");
    });
  }
});
