/** A toolkit-managed git checkout with one commit; returns its toplevel. */
function makeTree(label: string, settings: string | null): string {
  const root = join(tempDir(`ste774-${label}`), "repo");
  mkdirSync(root, { recursive: true });
  git(root, "init", "-q", "-b", "main");
  writeFileSync(join(root, "CLAUDE.md"), SETUP_MD);
  writeFileSync(join(root, "package.json"), '{"name":"fixture","version":"0.0.0","private":true}\n');
  if (settings !== null) {
    mkdirSync(join(root, "specs"), { recursive: true });
    writeFileSync(join(root, "specs", "settings.yaml"), settings);
  }
  git(root, "add", "-A");
  git(root, "commit", "-q", "-m", "fixture");
  return git(root, "rev-parse", "--show-toplevel").trim();
}

/** A plain dir (no git) holding only a settings file — for loader-only checks. */
function settingsTree(label: string, body: string | null): string {
  const root = tempDir(`ste774-${label}`);
  writeFileSync(join(root, "CLAUDE.md"), SETUP_MD);
  if (body !== null) {
    mkdirSync(join(root, "specs"), { recursive: true });
    writeFileSync(join(root, "specs", "settings.yaml"), body);
  }
  return root;
}

interface Run {
  exitCode: number;
  stdout: string;
  stderr: string;
}

function spawnBun(args: readonly string[], cwd: string): Run {
  const env: Record<string, string> = { ...(process.env as Record<string, string>), CLAUDE_CODE_SESSION_ID: SID };
  const p = spawnSync("bun", ["run", ...args], { cwd, env, encoding: "utf-8" });
  return { exitCode: p.status ?? -1, stdout: p.stdout ?? "", stderr: p.stderr ?? "" };
}

/** Write the result text to a file outside the root and run the record CLI on it. */
function record(root: string, reviewer: string, resultText: string): Run {
  const file = join(tempDir("ste774-result"), "result.md");
  writeFileSync(file, resultText);
  return spawnBun([RECORD_CLI, "record", root, reviewer, file], root);
}

function receiptPaths(root: string): string[] {
  const dir = receiptsDir(root, SID);
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((n) => n.endsWith(".json"))
    .sort()
    .map((n) => join(dir, n));
}

function reviewReceipts(root: string): AnyMod[] {
  return receiptPaths(root)
    .map((p) => JSON.parse(readFileSync(p, "utf-8")))
    .filter((r) => r.kind === KIND);
}

function onlyReviewReceipt(root: string): AnyMod {
  const all = reviewReceipts(root);
  expect(all.length).toBe(1);
  return all[0];
}

function describeRun(r: Run): string {
  return `exit ${r.exitCode}\n--- stdout\n${r.stdout}\n--- stderr\n${r.stderr}`;
}

function expectRefusal(r: Run): void {
  expect(r.exitCode, describeRun(r)).toBe(1);
  expect(r.stdout).toBe("");
  expect(r.stderr).toContain("Refusing:");
  expect(r.stderr.match(/^Remedy: /gm)?.length ?? 0).toBe(1);
  expect(r.stderr.match(/^Context: /gm)?.length ?? 0).toBe(1);
}

function caught(fn: () => unknown): unknown {
  let err: unknown = null;
  try {
    fn();
  } catch (e) {
    err = e;
  }
  return err;
}

