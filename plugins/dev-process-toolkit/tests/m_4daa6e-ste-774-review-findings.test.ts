/** Every local module reachable from `entries` through static and dynamic relative imports. */
function importGraph(entries: readonly string[]): Set<string> {
  const seen = new Set<string>();
  const queue = [...entries];
  const IMPORT_RE = /(?:from\s+|import\s*\(\s*|import\s+)["'](\.{1,2}\/[^"']+)["']/g;
  while (queue.length > 0) {
    const file = queue.pop()!;
    if (seen.has(file)) continue;
    seen.add(file);
    const text = readFileSync(file, "utf8");
    for (const m of text.matchAll(IMPORT_RE)) {
      const base = resolve(dirname(file), m[1]!);
      const candidates = [base, `${base}.ts`, join(base, "index.ts")];
      const hit = candidates.find((c) => existsSync(c) && c.endsWith(".ts"));
      if (hit !== undefined && !seen.has(hit)) queue.push(hit);
    }
  }
  return seen;
}

