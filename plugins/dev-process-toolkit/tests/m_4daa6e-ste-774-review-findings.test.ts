// STE-774 (M_4daa6e) — reviews record their finding counts, behind the opt-in
// switch `tracking.review_findings`.
//
// Modules under test:
//   adapters/_shared/src/project_settings.ts         — the `tracking.review_findings` leaf (AC-.1)
//   adapters/_shared/src/review_findings_receipt.ts  — `record <root> <reviewer> <result-file>` (AC-.2, AC-.3)
//   adapters/_shared/src/gate_receipt.ts             — the trailing `review_findings: on` switch line (AC-.4)
//   skills/{spec-review,tdd,implement}/SKILL.md      — the record call, gated on that line (AC-.4)
//   templates/hooks/_lib/hooks/<gate>.ts import graph — no gate reads the receipt (AC-.5)
//
// Receipt shape pinned here (one `review-findings` receipt per record call):
//   envelope: kind "review-findings", sessionId = CLAUDE_CODE_SESSION_ID
//   evidence.reviewer: the reviewer argument
//   evidence.head:     `git rev-parse HEAD` of the root
//   evidence.frs:      the FR ids named by the block's AC ids, sorted
//   evidence.counts:   spec reviewers — { <FR id>: { done, partial, missing } }
//                      code review    — { concerns: N }
//
// AC-STE-774.6 (mutation controls) — each guarded behaviour, and the named
// tests that red when it is removed:
//   - the parse (recording without parsing the block) ->
//       "AC-.3 spec-review: a malformed spec-review-result block writes no receipt and refuses"
//       "AC-.3 code-review: `OVERALL: CONCERNS` with no count writes no receipt and refuses"
//       "AC-.2 spec-review: counts done, partial and missing per FR"
//   - the switch check (record runs, or the line prints, with the switch off) ->
//       "AC-.4 switch off: record exits 0, prints nothing and writes no receipt"
//       "AC-.4 gate_receipt.ts <skill> with the switch off prints exactly the one announcement line"
//   - the refusal (a parse failure exiting 0 silently, or recording a zero) ->
//       "AC-.3 spec-review: a malformed spec-review-result block writes no receipt and refuses"
//       "AC-.3 code-review: a file with no OVERALL line writes no receipt and refuses"
//
// AC-STE-774.7 is the full-suite gate (`bun test` from plugins/dev-process-toolkit
// reports 0 failures, skip identities equal to trunk by name). It is graded by
// the gate run, not by a test in this file.
//
// Every tree is a temp git repo outside this checkout. All ids are synthetic.

