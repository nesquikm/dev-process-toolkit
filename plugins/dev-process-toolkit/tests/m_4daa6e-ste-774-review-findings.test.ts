/** The sentence splitter of the STE-715 mention rule (tests/_m_7bc805_gate_outcome_fixture.ts). */
function sentences(text: string): string[] {
  return text.split(/\n\s*\n/).flatMap((para) => para.replace(/\n/g, " ").split(/(?<=[.!?])\s+/));
}

const RECORD_RE = /review_findings_receipt\.ts"?\s+record\b/;

function section(text: string, startHeading: string, endHeadingPrefix: string): string {
  const start = text.indexOf(startHeading);
  if (start < 0) throw new Error(`heading not found: ${startHeading}`);
  const end = text.indexOf(endHeadingPrefix, start + startHeading.length);
  return end < 0 ? text.slice(start) : text.slice(start, end);
}

