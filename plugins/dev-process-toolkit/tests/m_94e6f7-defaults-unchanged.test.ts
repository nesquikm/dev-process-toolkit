function errOf(fn: () => unknown): unknown {
  try {
    return { value: fn() };
  } catch (e) {
    return { error: String((e as Error).message) };
  }
}

async function errOfAsync(fn: () => Promise<unknown>): Promise<unknown> {
  try {
    return { value: await fn() };
  } catch (e) {
    return { error: String((e as Error).message) };
  }
}

