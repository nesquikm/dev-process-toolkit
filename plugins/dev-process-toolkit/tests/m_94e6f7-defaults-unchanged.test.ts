interface Run {
  code: number;
  stdout: string;
  stderr: string;
}

async function runWrapper(wrapper: string, payload: string, cwd: string): Promise<Run> {
  const proc = Bun.spawn(["bash", wrapper], {
    cwd,
    env: { ...process.env, CLAUDE_PLUGIN_ROOT: PLUGIN, CLAUDE_CODE_SESSION_ID: SESSION, NO_COLOR: "1" },
    stdin: new Response(payload).body,
    stdout: "pipe",
    stderr: "pipe",
  });
  const [stdout, stderr] = await Promise.all([new Response(proc.stdout).text(), new Response(proc.stderr).text()]);
  return { code: await proc.exited, stdout, stderr };
}

function spawnBun(args: string[], cwd: string): Run {
  const r = Bun.spawnSync([process.execPath, "run", ...args], {
    cwd,
    env: { ...process.env, NO_COLOR: "1" },
    stdin: "ignore",
    stdout: "pipe",
    stderr: "pipe",
  });
  return { code: r.exitCode ?? -1, stdout: r.stdout.toString(), stderr: r.stderr.toString() };
}

function writeTranscript(dir: string, lines: unknown[]): string {
  const file = join(dir, "transcript.jsonl");
  writeFileSync(file, lines.map((l) => JSON.stringify(l)).join("\n") + (lines.length > 0 ? "\n" : ""));
  return file;
}

