const CITE_RE = /(?:<ROOT>\/)?(?:specs\/settings\.yaml|CLAUDE\.md|specs\/tracker-config\.yaml)(?::\d+)?/g;

/** (1): strings naming specs/settings.yaml compare with their citation tokens masked. */
function maskCitations(trunk: unknown, now: unknown): [unknown, unknown] {
  if (typeof trunk === "string" && typeof now === "string") {
    if (now !== trunk && now.includes("specs/settings.yaml")) return [trunk.replace(CITE_RE, "<CITE>"), now.replace(CITE_RE, "<CITE>")];
    return [trunk, now];
  }
  if (Array.isArray(trunk) && Array.isArray(now) && trunk.length === now.length) {
    const pairs = trunk.map((t, i) => maskCitations(t, now[i]));
    return [pairs.map((p) => p[0]), pairs.map((p) => p[1])];
  }
  if (trunk && now && typeof trunk === "object" && typeof now === "object" && !Array.isArray(trunk) && !Array.isArray(now)) {
    const t: Record<string, unknown> = {};
    const n: Record<string, unknown> = { ...(now as Record<string, unknown>) };
    for (const [k, v] of Object.entries(trunk as Record<string, unknown>)) {
      if (k in n) [t[k], n[k]] = maskCitations(v, n[k]);
      else t[k] = v;
    }
    return [t, n];
  }
  return [trunk, now];
}

const PROBE_69_ROW = /^settings-file \(\d+\.\d+\.\d+\): /;
const PROBE_69_REMEDY = "Remedy: run /dev-process-toolkit:upgrade to apply these migrations (Claude can invoke it; it is not on the slash menu).";

/** (2): drop exactly one warn-only settings-file row (and the remedy note it brings) from probe #69. */
function dropSettingsFileRow(trunk: unknown, now: unknown): unknown | string {
  const t = (trunk as { value?: { rows?: string[]; notes?: string[]; violations?: unknown[] } }).value;
  const n = (now as { value?: { rows?: string[]; notes?: string[]; violations?: unknown[] } }).value;
  if (!t || !n || !Array.isArray(n.rows)) return "probe #69 output is not a report";
  const extra = n.rows.filter((r) => PROBE_69_ROW.test(r) && !(t.rows ?? []).includes(r));
  if (extra.length !== 1) return `probe #69: ${extra.length} settings-file rows, the allowance admits exactly one`;
  const rows = n.rows.filter((r) => r !== extra[0]);
  let notes = (n.notes ?? []).filter((r) => r !== extra[0]);
  if ((t.notes ?? []).length === 0 && rows.length === 0) notes = notes.filter((r) => r !== PROBE_69_REMEDY);
  return { ...(now as object), value: { ...n, rows, notes } };
}

/** (3) for the probe #21 message: only the tracker-metadata destination sentence may change, and only to `## Tracker Notes`. */
function trackerNotesRemedy(trunk: string, now: string): string | null {
  if (trunk === now) return null;
  const split = (s: string) => s.split(/(?<=\.)\s+/);
  const a = split(trunk);
  const b = split(now);
  if (a.length !== b.length) return "probe #21 remedy: sentence count changed";
  for (let i = 0; i < a.length; i++) {
    if (a[i] === b[i]) continue;
    if (!/sub-heading|### /.test(a[i]!)) return `probe #21 remedy: a sentence other than the destination changed: ${b[i]}`;
    if (!b[i]!.includes("## Tracker Notes") || /### /.test(b[i]!) || /sub-heading/.test(b[i]!)) {
      return `probe #21 remedy: the destination sentence does not name ## Tracker Notes alone: ${b[i]}`;
    }
  }
  return null;
}

/**
 * (3) for the helper's diff: the file headers, the context lines and the removed
 * lines are unchanged; only the hunk header's counts and the added lines move —
 * trunk's re-added stray keys become `- key: value` under `+## Tracker Notes`.
 */
function trackerNotesDiff(trunk: string, now: string): string | null {
  if (trunk === now) return null;
  const lines = (d: string) => d.split("\n").filter((l) => !/^@@ .* @@$/.test(l));
  const headers = (d: string) => lines(d).filter((l) => l.startsWith("--- ") || l.startsWith("+++ "));
  const rest = (d: string) => lines(d).filter((l) => !(l.startsWith("--- ") || l.startsWith("+++ ")));
  const context = (d: string) => rest(d).filter((l) => !l.startsWith("+") && !l.startsWith("-"));
  const minus = (d: string) => rest(d).filter((l) => l.startsWith("-"));
  const plus = (d: string) => rest(d).filter((l) => l.startsWith("+")).map((l) => l.slice(1)).filter((l) => l.trim() !== "");
  if (JSON.stringify(headers(trunk)) !== JSON.stringify(headers(now))) return "helper diff: the file headers changed";
  if (JSON.stringify(context(trunk)) !== JSON.stringify(context(now))) return "helper diff: the context lines changed";
  if (JSON.stringify(minus(trunk)) !== JSON.stringify(minus(now))) return "helper diff: the removed lines changed";
  const want = ["## Tracker Notes", ...plus(trunk).map((l) => `- ${l}`)];
  if (JSON.stringify(plus(now)) !== JSON.stringify(want)) return `helper diff: added ${JSON.stringify(plus(now))}, want ${JSON.stringify(want)}`;
  return null;
}

/** Compare one compared output against its pinned literal; returns the differences no allowance explains. */
function compare(fixture: Fixture, key: string, trunk: unknown, now: unknown): { diffs: string[]; used: Allowance[] } {
  const scope = key.startsWith("reader ") ? [] : ALLOWANCE_SCOPE[fixture];
  const used: Allowance[] = [];
  let t = trunk;
  let n = now;
  if (JSON.stringify(t) === JSON.stringify(n)) return { diffs: [], used };

  if (key === "probe #69" && scope.includes("probe-69-settings-file-row")) {
    const r = dropSettingsFileRow(t, n);
    if (typeof r === "string") return { diffs: [r], used };
    n = r;
    used.push("probe-69-settings-file-row");
  }
  if (scope.includes("probe-21-tracker-notes-destination")) {
    if (key === "helper migrate-task-tracking-canonical") {
      const tv = (t as { value?: unknown }).value;
      const nv = (n as { value?: unknown }).value;
      if (typeof tv === "string" && typeof nv === "string" && tv !== nv) {
        const why = trackerNotesDiff(tv, nv);
        if (why) return { diffs: [why], used };
        n = t;
        used.push("probe-21-tracker-notes-destination");
      }
    }
    if (key === "probe #21") {
      const tv = (t as { value?: { violations?: { message?: string }[] } }).value?.violations ?? [];
      const nv = (n as { value?: { violations?: { message?: string }[] } }).value?.violations ?? [];
      if (tv.length === nv.length && tv.length > 0) {
        const fixed = nv.map((v, i) => {
          const why = trackerNotesRemedy(String(tv[i]!.message), String(v.message));
          return why ? v : { ...v, message: tv[i]!.message };
        });
        if (JSON.stringify(fixed) !== JSON.stringify(nv)) used.push("probe-21-tracker-notes-destination");
        n = { ...(n as object), value: { ...(n as { value: object }).value, violations: fixed } };
      }
    }
  }
  if (scope.includes("settings-yaml-citation") && JSON.stringify(t) !== JSON.stringify(n)) {
    const [mt, mn] = maskCitations(t, n);
    if (JSON.stringify(mt) === JSON.stringify(mn)) used.push("settings-yaml-citation");
    t = mt;
    n = mn;
  }
  return { diffs: JSON.stringify(t) === JSON.stringify(n) ? [] : [`${fixture} / ${key}: ${JSON.stringify(n)} != pinned ${JSON.stringify(t)}`], used };
}

