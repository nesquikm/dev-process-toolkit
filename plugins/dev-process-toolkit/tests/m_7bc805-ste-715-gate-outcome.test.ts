describe("AC-STE-715.14 the switch shape", () => {
  test("an absent key reads enabled: false; { enabled: true } reads true; a bare `gate_outcomes: true` throws SettingsShapeError", async () => {
    const m = await S();
    const absent = settingsTree("sw-absent", `${SETTINGS_HEAD}tracking:\n  token_stats:\n    enabled: false\n`);
    expect(m.loadProjectSection(absent, "tracking").gate_outcomes.enabled).toBe(false);
    const on = settingsTree("sw-on", `${SETTINGS_HEAD}tracking:\n  gate_outcomes:\n    enabled: true\n`);
    expect(m.loadProjectSection(on, "tracking").gate_outcomes.enabled).toBe(true);
    const bare = settingsTree("sw-bare", `${SETTINGS_HEAD}tracking:\n  gate_outcomes: true\n`);
    expect(() => m.loadProjectSection(bare, "tracking")).toThrow(m.SettingsShapeError);
  });

  test("settingsKeyOrder names gate_outcomes; tracking.gate_outcomes closes on {enabled}; NEW_KEYS holds it", async () => {
    const m = await S();
    // Amended by AC-STE-716.24 (M_7bc805): STE-716 adds tool_calls after gate_outcomes in the tracking key order.
    // Amended by AC-STE-774.1 (M_4daa6e): STE-774 adds review_findings after tool_calls.
    expect(m.settingsKeyOrder("tracking")).toEqual(["token_stats", "gate_outcomes", "tool_calls", "review_findings"]);
    expect(m.settingsKeyOrder("tracking.gate_outcomes")).toEqual(["enabled"]);
    expect(m.NEW_KEYS).toContain("tracking.gate_outcomes");
  });

  test("gateOutcomesSwitchOn: true only for an explicit true; legacy, none, false, absent and a malformed token_stats read off", async () => {
    const m = await S();
    expect(typeof m.gateOutcomesSwitchOn).toBe("function");
    expect(m.gateOutcomesSwitchOn(makeTree("gso-on", "on"))).toBe(true);
    for (const state of ["false", "absent", "legacy", "none"] as const) {
      expect({ state, on: m.gateOutcomesSwitchOn(makeTree(`gso-${state}`, state)) }).toEqual({ state, on: false });
    }
    const malformed = settingsTree(
      "gso-malformed",
      `${SETTINGS_HEAD}tracking:\n  token_stats: yes\n  gate_outcomes:\n    enabled: true\n`,
    );
    expect(() => m.gateOutcomesSwitchOn(malformed)).not.toThrow();
    expect(m.gateOutcomesSwitchOn(malformed)).toBe(false);
  });

  test("a legacy tree reads tracking.gate_outcomes.enabled: false beside token_stats", async () => {
    const m = await S();
    const root = makeTree("legacy-read", "legacy");
    const tr = m.loadProjectSection(root, "tracking");
    expect(tr.gate_outcomes).toEqual({ enabled: false });
    expect(tr.token_stats).toBeDefined();
  });

  test("docs/settings-reference.md names tracking.gate_outcomes with its default, as a new STE-715 key", () => {
    const doc = readFileSync(join(PLUGIN_ROOT, "docs", "settings-reference.md"), "utf-8");
    const row = doc.split("\n").find((l) => l.startsWith("| `tracking.gate_outcomes` |"));
    expect(row).toBeDefined();
    expect(row!).toContain("`{ enabled: false }`");
    expect(row!).toContain("STE-715");
    expect(row!).toMatch(/no legacy home/);
  });

  // The AC-STE-706.12 walk, re-run against the MAPPING table of the loader suite
  // with and without the new row (the table is read from that suite's source).
  const LOADER_SUITE = join(PLUGIN_ROOT, "tests", "m_94e6f7-ste-706-settings-loader.test.ts");
  const ROW = '"tracking.gate_outcomes": { kind: "new", fr: "STE-715", note: "no legacy home" },';

  function blockOf(src: string, opener: string, closer: string): string {
    const at = src.indexOf(opener);
    expect(at).toBeGreaterThanOrEqual(0);
    return src.slice(at, src.indexOf(closer, at));
  }

  function mappedKeys(src: string): Set<string> {
    const block = blockOf(src, "const MAPPING: Record<string, Row> = {", "\n};");
    const keys = new Set<string>();
    for (const m of block.matchAll(/^\s+"?([a-z_]+(?:\.[a-z_]+)*)"?:\s*\{\s*kind:/gm)) keys.add(m[1]!);
    // BINDING_KEYS rows are generated, not written; they are not under test here.
    return keys;
  }

  function leafBlocks(src: string): Set<string> {
    const block = blockOf(src, "const LEAF_BLOCKS = new Set([", "]);");
    return new Set([...block.matchAll(/"([a-z_.]+)"/g)].map((m) => m[1]!));
  }

  async function unmapped(keys: Set<string>, leaves: Set<string>): Promise<string[]> {
    const order = (await S()).settingsKeyOrder as (p: string) => readonly string[];
    const walk = (prefix: string): string[] => {
      const out: string[] = [];
      for (const k of order(prefix)) {
        const p = prefix ? `${prefix}.${k}` : k;
        if (leaves.has(p) || order(p).length === 0) out.push(p);
        else out.push(...walk(p));
      }
      return out;
    };
    return walk("").filter((p) => p.startsWith("tracking") && !keys.has(p));
  }

  test("the AC-STE-706.12 table holds the new row, LEAF_BLOCKS holds the path, and the walk finds it mapped", async () => {
    const src = readFileSync(LOADER_SUITE, "utf-8");
    expect(src).toContain(ROW);
    expect(leafBlocks(src).has("tracking.gate_outcomes")).toBe(true);
    expect(await unmapped(mappedKeys(src), leafBlocks(src))).toEqual([]);
  });

  test("CONTROL: deleting the new MAPPING row in a temp copy turns the walk red", async () => {
    const src = readFileSync(LOADER_SUITE, "utf-8");
    const copy = src.replace(ROW, "");
    expect(copy).not.toBe(src);
    expect(await unmapped(mappedKeys(copy), leafBlocks(copy))).toEqual(["tracking.gate_outcomes"]);
  });

  test("source scan: gate_receipt.ts imports neither project_settings nor gate_reuse_key statically", () => {
    const src = readFileSync(join(SRC, "gate_receipt.ts"), "utf-8");
    const statics = [...src.matchAll(/^\s*(?:import|export)\b[^;]*?from\s+["']([^"']+)["']/gm)].map((m) => m[1]!);
    const bare = [...src.matchAll(/^\s*import\s+["']([^"']+)["']/gm)].map((m) => m[1]!);
    for (const spec of [...statics, ...bare]) {
      expect({ spec, bad: /(^|\/)(project_settings|gate_reuse_key)(\.ts)?$/.test(spec) }).toEqual({ spec, bad: false });
    }
    // Both are loaded by dynamic import() instead.
    expect(src).toMatch(/import\(\s*["'][^"']*project_settings(\.ts)?["']\s*\)/);
    expect(src).toMatch(/import\(\s*["'][^"']*gate_reuse_key(\.ts)?["']\s*\)/);
  });

  test("source scan: recordGateRun is declared async and its one CLI call is awaited; no other caller ships", () => {
    const src = readFileSync(join(SRC, "gate_receipt.ts"), "utf-8");
    expect(src).toMatch(/export async function recordGateRun\(/);
    const calls = [...src.matchAll(/(\bawait\s+)?\brecordGateRun\(/g)].filter(
      (m) => !src.slice(Math.max(0, m.index! - 30), m.index!).includes("function "),
    );
    expect(calls.length).toBe(1);
    expect(calls[0]![1]).toBeDefined();
    const shipped = Bun.spawnSync(
      ["grep", "-rlE", "recordGateRun\\(", join(PLUGIN_ROOT, "adapters"), join(PLUGIN_ROOT, "templates"), join(PLUGIN_ROOT, "scripts")],
      { stdout: "pipe" },
    ).stdout.toString().split("\n").filter((l) => l.length > 0);
    expect(shipped).toEqual([join(SRC, "gate_receipt.ts")]);
  });

  const MARKER_MODULE = (marker: string): string =>
    [
      'import { writeFileSync } from "node:fs";',
      `writeFileSync(${JSON.stringify(marker)}, "loaded\\n");`,
      "export function gateReuseKey(): never { throw new Error(\"marker stub\"); }",
      "export function reuseKeyDigest(): never { throw new Error(\"marker stub\"); }",
      "export function worktreeDigest(): never { throw new Error(\"marker stub\"); }",
      "",
    ].join("\n");

  test("MARKER: pre-commit-gate-check through its wrapper never loads gate_reuse_key.ts (switch on)", async () => {
    const copy = pluginCopy("marker");
    const marker = join(tempDir("marker-out"), "loaded.txt");
    writeFileSync(join(copy, "adapters", "_shared", "src", "gate_reuse_key.ts"), MARKER_MODULE(marker));
    // CONTROL: loading the stub writes the marker, so its absence below means something.
    Bun.spawnSync(["bun", "-e", `await import(${JSON.stringify(join(copy, "adapters", "_shared", "src", "gate_reuse_key.ts"))})`]);
    expect(existsSync(marker)).toBe(true);
    Bun.spawnSync(["rm", "-f", marker]);

    const root = makeTree("marker-tree", "on");
    const door = join(copy, "adapters", "_shared", "src", "gate_receipt.ts");
    const r = runCli(["gate-check", root], { frontDoor: door, env: { CLAUDE_PLUGIN_ROOT: copy } });
    expect(r.exitCode).toBe(0);
    // The receipt CLI with the switch on DOES load it (dynamic import once on).
    expect(existsSync(marker)).toBe(true);
    Bun.spawnSync(["rm", "-f", marker]);

    const tr = writeTranscript(tempDir("tr"), [...skillCall("gate"), ...bashCall("b1", receiptCommand("gate-check", root), r.stdout)]);
    await runHook("gate", root, tr, { pluginRoot: copy });
    expect(existsSync(marker)).toBe(false);
  }, T);

  test("MARKER: with the switch off the receipt CLI never loads gate_reuse_key.ts", () => {
    const copy = pluginCopy("marker-off");
    const marker = join(tempDir("marker-off-out"), "loaded.txt");
    writeFileSync(join(copy, "adapters", "_shared", "src", "gate_reuse_key.ts"), MARKER_MODULE(marker));
    const root = makeTree("marker-off-tree", "absent");
    const door = join(copy, "adapters", "_shared", "src", "gate_receipt.ts");
    const r = runCli(["gate-check", root], { frontDoor: door, env: { CLAUDE_PLUGIN_ROOT: copy } });
    expect(r.exitCode).toBe(0);
    expect(existsSync(marker)).toBe(false);
  }, T);
});

