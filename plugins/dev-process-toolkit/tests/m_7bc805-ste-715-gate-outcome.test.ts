type AnyMod = Record<string, any>;
const T = 120_000;

afterAll(cleanupTemps);

async function S(): Promise<AnyMod> {
  return (await import("../adapters/_shared/src/project_settings")) as AnyMod;
}

function settingsTree(label: string, body: string, claudeMd = "<!-- generated by /dev-process-toolkit:setup -->\n# P\n"): string {
  const root = tempDir(label);
  mkdirSync(join(root, "specs"), { recursive: true });
  writeFileSync(join(root, "specs", "settings.yaml"), body);
  writeFileSync(join(root, "CLAUDE.md"), claudeMd);
  return root;
}

function trackingLines(root: string): string[] {
  const lines = readFileSync(join(root, "specs", "settings.yaml"), "utf-8").split("\n");
  const start = lines.findIndex((l) => l === "tracking:" || l.startsWith("tracking:"));
  if (start < 0) return [];
  let end = start + 1;
  while (end < lines.length && (lines[end]!.startsWith(" ") || lines[end] === "")) end++;
  return lines.slice(start, end);
}

