const SETUP_SKILL = join(PLUGIN, "skills", "setup", "SKILL.md");
const SETUP_REFERENCE = join(PLUGIN, "docs", "setup-reference.md");
const CREATE_CALL = /`writeProjectSettings\(projectRoot, (.+?), \{ create: true \}\)`/g;

// The v3.5.0 bytes, measured (see the header note) — pasted literals.
const V350_CREATE = "schema_version: 1\nmin_dpt_version: 3.0.0\n";
const V350_WITH_SECTIONS =
  "schema_version: 1\nmin_dpt_version: 3.0.0\ntask_tracking:\n  mode: none\norchestration:\n  default_effort: high\n  merge_policy: offer\n";

function createArgs(file: string): string[] {
  return [...readFileSync(file, "utf8").matchAll(CREATE_CALL)].map((m) => m[1]!);
}

/** The initial object of /setup's create call, as SKILL.md names it. */
function setupCreateInitial(): Record<string, unknown> {
  const args = createArgs(SETUP_SKILL);
  if (args.length !== 1) throw new Error(`skills/setup/SKILL.md names ${args.length} create calls, expected exactly 1`);
  return new Function(`return (${args[0]});`)() as Record<string, unknown>;
}

/** Run /setup's create call on a fresh tree (CLAUDE.md as /setup leaves it, no settings file). */
async function setupCreate(label: string): Promise<string> {
  const m = await settingsMod();
  const root = tree(label, null);
  m.writeProjectSettings(root, setupCreateInitial(), { create: true });
  return root;
}

/** Split a settings file into its column-0 `retro:` block and everything else. */
function splitRetro(text: string): { retro: string; rest: string } {
  const lines = text.split("\n");
  const at = lines.findIndex((l) => l === "retro:" || l.startsWith("retro: "));
  if (at < 0) return { retro: "", rest: text };
  let end = at + 1;
  while (end < lines.length && (lines[end]!.startsWith(" ") || lines[end]!.startsWith("\t"))) end++;
  return {
    retro: `${lines.slice(at, end).join("\n")}\n`,
    rest: [...lines.slice(0, at), ...lines.slice(end)].join("\n"),
  };
}

