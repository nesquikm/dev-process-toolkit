async function registry(): Promise<AnyMod[]> {
  return (await import(MIGRATIONS_MOD)).MIGRATIONS as AnyMod[];
}

async function registryEntry(id: string): Promise<AnyMod> {
  const e = (await registry()).find((m) => m.id === id);
  if (e === undefined) throw new Error(`migration registry holds no entry with id "${id}"`);
  return e;
}

/** The ids of every registry entry whose detect applies to `root`. */
async function pending(root: string): Promise<string[]> {
  return (await registry()).filter((e) => e.detect(root).applies).map((e) => e.id as string);
}

/** One /upgrade walk: apply every script entry whose detect applies, in order; a refusal throws. */
async function walk(root: string): Promise<string[]> {
  const changed: string[] = [];
  for (const e of await registry()) {
    if (e.kind !== "script" || typeof e.apply !== "function") continue;
    if (!e.detect(root).applies) continue;
    const r = e.apply(root);
    if (/Refusing:/.test(r.summary)) throw new Error(`${e.id} refused during the walk:\n${r.summary}`);
    changed.push(...(r.changed as string[]).map((c) => `${e.id}:${c}`));
  }
  return changed;
}

function treeBytes(root: string): Record<string, string> {
  const out: Record<string, string> = { "CLAUDE.md": readFileSync(join(root, "CLAUDE.md"), "utf8") };
  if (existsSync(join(root, "specs", "settings.yaml"))) out["specs/settings.yaml"] = settingsBytes(root);
  return out;
}

/** Apply the settings-file move to a fresh legacy managed tree; the move must report it created the file. */
async function moveLegacy(label: string): Promise<string> {
  const move = await registryEntry(MOVE_ID);
  const root = tree(label, null, MOVE_LEGACY_MD);
  expect(move.detect(root).applies).toBe(true);
  const res = move.apply(root);
  expect(res.changed).toContain("specs/settings.yaml");
  return root;
}

