// eslint-disable-next-line @typescript-eslint/no-explicit-any
type AnyMod = any;

async function settingsMod(): Promise<AnyMod> {
  return await import(SETTINGS_MOD);
}

async function migrationEntry(): Promise<AnyMod> {
  const reg = await import(MIGRATIONS_MOD);
  const entry = (reg.MIGRATIONS as AnyMod[]).find((e) => e.id === ENTRY_ID);
  if (entry === undefined) throw new Error(`migration registry holds no entry with id "${ENTRY_ID}"`);
  return entry;
}

const temps: string[] = [];
afterAll(() => {
  for (const t of temps) rmSync(t, { recursive: true, force: true });
});

function tempDir(label: string): string {
  const d = mkdtempSync(join(tmpdir(), `ste775-${label}-`));
  temps.push(d);
  return d;
}

/** A tree with CLAUDE.md and, when `body` is non-null, a `specs/settings.yaml`. */
function tree(label: string, body: string | null, claudeMd: string = SETUP_MD): string {
  const root = tempDir(label);
  writeFileSync(join(root, "CLAUDE.md"), claudeMd);
  if (body !== null) {
    mkdirSync(join(root, "specs"), { recursive: true });
    writeFileSync(join(root, "specs", "settings.yaml"), body);
  }
  return root;
}

function settingsBytes(root: string): string {
  return readFileSync(join(root, "specs", "settings.yaml"), "utf8");
}

function parsedSettings(root: string): AnyMod {
  return Bun.YAML.parse(settingsBytes(root));
}

function priorityYaml(items: string): string {
  return `${SETTINGS_HEAD}retro:\n  enabled: true\n  priority: ${items}\n`;
}

function caught(fn: () => unknown): unknown {
  let err: unknown = null;
  try {
    fn();
  } catch (e) {
    err = e;
  }
  return err;
}

function runGet(section: string, root: string): { status: number | null; stdout: string; stderr: string } {
  const r = spawnSync("bun", ["run", SETTINGS_MOD, "get", section, root], { encoding: "utf8", cwd: root });
  return { status: r.status, stdout: r.stdout, stderr: r.stderr };
}

