export const GIT_ENV: Record<string, string> = {
  GIT_CONFIG_GLOBAL: "/dev/null",
  GIT_CONFIG_SYSTEM: "/dev/null",
  GIT_AUTHOR_NAME: "F",
  GIT_AUTHOR_EMAIL: "f@example.invalid",
  GIT_COMMITTER_NAME: "F",
  GIT_COMMITTER_EMAIL: "f@example.invalid",
};

export function git(cwd: string, ...args: string[]): string {
  const p = spawnSync("git", args, { cwd, encoding: "utf-8", env: { ...process.env, ...GIT_ENV } });
  if (p.status !== 0) throw new Error(`git ${args.join(" ")}: ${p.stderr}`);
  return p.stdout ?? "";
}

/** The bytes of a repo-relative path at the v3.0.0 merge commit. */
export function atV300(repoRel: string): string {
  const p = spawnSync("git", ["show", `${V300}:${repoRel}`], {
    cwd: REPO_ROOT,
    encoding: "utf-8",
    maxBuffer: 64 * 1024 * 1024,
  });
  if (p.status !== 0) throw new Error(`git show ${V300}:${repoRel}: ${p.stderr}`);
  return p.stdout ?? "";
}

