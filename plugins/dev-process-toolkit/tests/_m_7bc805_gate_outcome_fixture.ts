// --------------------------------------------------------------- hooks

export function hookWrapper(hook: Hook, pluginRoot = PLUGIN_ROOT): string {
  const name = { gate: "pre-commit-gate-check", tdd: "pre-commit-tdd-orchestrator", pr: "pre-pr-spec-review" }[hook];
  return join(pluginRoot, "templates", "hooks", "process", `${name}.sh`);
}

export function hookCommand(hook: Hook, root: string): string {
  return hook === "pr" ? "gh pr create --fill" : `git -C ${root} commit -m x`;
}

export async function runHook(
  hook: Hook,
  root: string,
  transcriptPath: string,
  opts: { pluginRoot?: string; env?: Record<string, string> } = {},
): Promise<CliRun> {
  const pluginRoot = opts.pluginRoot ?? PLUGIN_ROOT;
  const payload = {
    transcript_path: transcriptPath,
    cwd: root,
    hook_event_name: "PreToolUse",
    tool_name: "Bash",
    tool_input: { command: hookCommand(hook, root) },
    session_id: SID,
  };
  const proc = Bun.spawn(["/bin/bash", hookWrapper(hook, pluginRoot)], {
    cwd: root,
    env: { ...process.env, ...GIT_ENV, CLAUDE_PLUGIN_ROOT: pluginRoot, ...(opts.env ?? {}) },
    stdin: new Response(JSON.stringify(payload)).body,
    stdout: "pipe",
    stderr: "pipe",
  });
  const [stdout, stderr] = await Promise.all([new Response(proc.stdout).text(), new Response(proc.stderr).text()]);
  return { exitCode: await proc.exited, stdout, stderr };
}

// ------------------------------------------------------- sentence model

/** The sentence splitter of the AC-STE-708.13 guard (tests/m_94e6f7-ste-708-mode-front-door.test.ts). */
export function sentences(text: string): string[] {
  return text
    .split(/\n\s*\n/)
    .flatMap((para) => para.replace(/\n/g, " ").split(/(?<=[.!?])\s+/));
}

/** A sentence names the outcome verb when it orders the front door with `outcome`. */
export const OUTCOME_VERB_RE = /gate_receipt\.ts"?\s+outcome\b/;

/** Every sentence of `text` naming the outcome verb without the backticked `outcome: on` line. */
export function mentionRuleViolations(text: string): string[] {
  return sentences(text)
    .filter((s) => OUTCOME_VERB_RE.test(s) && !s.includes("`outcome: on`"))
    .map((s) => s.slice(0, 160));
}
