// STE-715 (M_7bc805) shared fixture helper — gate outcome records.
//
// Leading underscore: a helper module, never collected as a suite.
//
// Every receipt a STE-715 suite puts into a fixture is written by SPAWNING the
// shipped front door, never by a hand-rolled JSON write (the STE-614 rule).
// Every git call runs with a neutral config, so a developer's global git
// config cannot move a key or a verdict.

