export function clearStore(root: string, sid = SID): void {
  rmSync(receiptDirOf(root, sid), { recursive: true, force: true });
}

export function readJson(path: string): Record<string, unknown> {
  return JSON.parse(readFileSync(path, "utf-8")) as Record<string, unknown>;
}

/** Parse a `<prefix><abs path> sha256:<hex>` announcement line. */
export function parseAnnouncement(line: string, prefix: string): { path: string; digest: string } | null {
  if (!line.startsWith(prefix)) return null;
  const m = /^(\/.*\S)\s+sha256:([0-9a-f]{64})$/.exec(line.slice(prefix.length));
  return m ? { path: m[1]!, digest: m[2]! } : null;
}

/** Run the receipt CLI and return the run, its announcement line and the receipt path. */
export function mintRun(
  root: string,
  skill = "gate-check",
  opts: { sid?: string; env?: Record<string, string>; frontDoor?: string } = {},
): { run: CliRun; line: string; path: string } {
  const run = runCli([skill, root], { sid: opts.sid, env: opts.env, frontDoor: opts.frontDoor });
  if (run.exitCode !== 0) throw new Error(`receipt CLI failed (exit ${run.exitCode}): ${run.stderr}`);
  const line = run.stdout.split("\n")[0] ?? "";
  const parsed = parseAnnouncement(line, "dpt-receipt: ");
  if (parsed === null) throw new Error(`receipt CLI printed no announcement: ${run.stdout}`);
  return { run, line, path: parsed.path };
}

// ------------------------------------------------------- plugin temp copies

/**
 * A temp copy of the plugin's runtime tree (adapters, templates, skills, hooks,
 * manifest) — enough to run the front door and the hook wrappers from it.
 */
export function pluginCopy(label: string): string {
  const dst = join(tempDir(label), "plugin");
  mkdirSync(dst, { recursive: true });
  for (const part of ["adapters", "templates", "skills", "hooks", ".claude-plugin", "bunfig.toml"]) {
    const from = join(PLUGIN_ROOT, part);
    if (existsSync(from)) cpSync(from, join(dst, part), { recursive: true });
  }
  return dst;
}

